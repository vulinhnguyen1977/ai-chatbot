"""Step 7 -- build the `mstutor` Ollama model.

This is the only step that is mandatory. It bakes the teaching contract from
src/prompts.h into a model derived from a base you already have, and attaches
the fine-tuned LoRA adapter if steps 5 and 6 have produced one.

    python training/7_build_ollama_model.py
    python training/7_build_ollama_model.py --base qwen3:8b --name mstutor

Run it again whenever src/prompts.h changes.
"""

from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
from pathlib import Path

from common import ADAPTERS, ROOT, read_tutor_system_prompt

DEFAULT_BASE = "qwen3:4b"
DEFAULT_NAME = "mstutor"


def find_ollama() -> str:
    """Locate the ollama executable, including the default Windows install
    directory that the installer does not always add to PATH."""
    found = shutil.which("ollama")
    if found:
        return found
    candidates = [
        Path.home() / "AppData/Local/Programs/Ollama/ollama.exe",
        Path("C:/Program Files/Ollama/ollama.exe"),
        Path("/usr/local/bin/ollama"),
        Path("/usr/bin/ollama"),
    ]
    for candidate in candidates:
        if candidate.exists():
            return str(candidate)
    sys.exit(
        "Could not find the 'ollama' command.\n"
        "Install it from https://ollama.com/download, then re-run this script."
    )


def installed_models(ollama: str) -> list[str]:
    try:
        out = subprocess.run([ollama, "list"], capture_output=True, text=True, timeout=60)
    except (OSError, subprocess.SubprocessError):
        return []
    names = []
    for line in out.stdout.splitlines()[1:]:
        parts = line.split()
        if parts:
            names.append(parts[0])
    return names


def build_modelfile(base: str, system_prompt: str, adapter: Path | None) -> str:
    lines = [
        f"FROM {base}",
        "",
        "# Generated by training/7_build_ollama_model.py -- do not edit by hand.",
        "# The system prompt is copied verbatim from src/prompts.h so the served",
        "# behaviour and the trained behaviour cannot drift apart.",
        "",
    ]

    if adapter is not None:
        lines += [
            "# LoRA adapter from the fine-tuning steps. It must have been trained",
            "# against this same base model.",
            f"ADAPTER {adapter.as_posix()}",
            "",
        ]

    lines += [
        "# Low temperature: arithmetic, not creative writing.",
        "PARAMETER temperature 0.2",
        "PARAMETER top_p 0.9",
        "PARAMETER top_k 40",
        "# Discourage the model from restating the same step repeatedly.",
        "PARAMETER repeat_penalty 1.1",
        "# Room for the system prompt, retrieved textbook passages and history.",
        "PARAMETER num_ctx 8192",
        "",
        'SYSTEM """',
        system_prompt,
        '"""',
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--base", default=DEFAULT_BASE, help=f"base model (default {DEFAULT_BASE})")
    parser.add_argument("--name", default=DEFAULT_NAME, help=f"model name (default {DEFAULT_NAME})")
    parser.add_argument("--adapter", default=None, help="path to a GGUF LoRA adapter")
    parser.add_argument("--print-only", action="store_true", help="show the Modelfile and stop")
    args = parser.parse_args()

    system_prompt = read_tutor_system_prompt()
    print(f"Teaching prompt: {len(system_prompt)} characters from src/prompts.h")

    adapter: Path | None = None
    if args.adapter:
        adapter = Path(args.adapter).resolve()
        if not adapter.exists():
            sys.exit(f"Adapter not found: {adapter}")
    else:
        # Pick up a fine-tuned adapter automatically if one has been exported.
        auto = sorted(ADAPTERS.glob("*.gguf")) if ADAPTERS.exists() else []
        if auto:
            adapter = auto[-1].resolve()
            print(f"Found fine-tuned adapter: {adapter.name}")

    if adapter is None:
        print("No LoRA adapter found -- building a prompt-only model.")
        print("  (That is a complete, working tutor. Steps 4-6 add the fine-tune.)")

    modelfile = build_modelfile(args.base, system_prompt, adapter)
    path = ROOT / "training" / "Modelfile"
    path.write_text(modelfile, encoding="utf-8")
    print(f"Wrote {path}")

    if args.print_only:
        print("\n" + "-" * 60)
        print(modelfile)
        return 0

    ollama = find_ollama()
    print(f"Using {ollama}")

    installed = installed_models(ollama)
    if installed and not any(m == args.base or m.startswith(args.base + ":") for m in installed):
        print(f"\nBase model '{args.base}' is not installed. Pulling it now...")
        pull = subprocess.run([ollama, "pull", args.base])
        if pull.returncode != 0:
            return pull.returncode

    print(f"\nCreating '{args.name}' from '{args.base}'...")
    # `ollama create` resolves relative paths in the Modelfile against its
    # working directory, so run it from the file's own folder.
    result = subprocess.run(
        [ollama, "create", args.name, "-f", str(path)],
        cwd=str(path.parent),
    )
    if result.returncode != 0:
        print("\nModel creation failed. Check that Ollama is running (`ollama serve`).")
        return result.returncode

    print(f"\nDone. '{args.name}' is ready.")
    print(f"Try it:  ollama run {args.name} \"What is 3/4 + 1/6?\"")
    print("Then start the app and ask a question in the browser.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
